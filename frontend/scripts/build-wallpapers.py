#!/usr/bin/env python3
"""Wallpapers: converts raw PNGs (default ~/wall_raw/{n,a,s,q}NN.png) into public/wallpapers/<id>.webp
(768 px wide, q72) + t/<id>.webp thumbnails (180 px, q60), then rewrites src/lib/wallpaperList.js
from every WebP present (n* = nature, a* = anime, s* = seas & oceans (9.0), q* = Iraq (9.0)) with
an average colour each. A raw picture that isn't 9:16 is cropped to it around the centre.
  python3 scripts/build-wallpapers.py [raw_dir]      (needs Pillow)"""
import os, sys, glob
from PIL import Image
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RAW = sys.argv[1] if len(sys.argv) > 1 else os.path.expanduser('~/wall_raw')
OUT = os.path.join(ROOT, 'public', 'wallpapers')
os.makedirs(os.path.join(OUT, 't'), exist_ok=True)
for p in sorted(glob.glob(os.path.join(RAW, '*.png'))):
    wid = os.path.basename(p)[:-4]
    im = Image.open(p).convert('RGB')
    want = 768 / 1376
    if abs(im.width / im.height - want) > 0.01:          # centre-crop to the phone's 9:16
        if im.width / im.height > want:
            nw = round(im.height * want); x = (im.width - nw) // 2; im = im.crop((x, 0, x + nw, im.height))
        else:
            nh = round(im.width / want); y = (im.height - nh) // 2; im = im.crop((0, y, im.width, y + nh))
    if im.width > 768: im = im.resize((768, round(im.height * 768 / im.width)), Image.LANCZOS)
    im.save(os.path.join(OUT, wid + '.webp'), 'WEBP', quality=72, method=6)
    im.resize((180, round(im.height * 180 / im.width)), Image.LANCZOS).save(os.path.join(OUT, 't', wid + '.webp'), 'WEBP', quality=60, method=6)
rows = {'n': [], 'a': [], 's': [], 'q': []}
for p in sorted(glob.glob(os.path.join(OUT, '*.webp'))):
    wid = os.path.basename(p)[:-5]
    if wid[0] not in rows: continue
    c = Image.open(p).convert('RGB').resize((1, 1), Image.BOX).getpixel((0, 0))
    rows[wid[0]].append("['%s', '#%02x%02x%02x']" % ((wid,) + c))
js = ("// Generated by scripts/build-wallpapers.py — the bundled wallpapers (files in public/wallpapers/),\n"
      "// with an average colour each for the placeholder while a photo loads.\n"
      "export const NATURE = [" + ', '.join(rows['n']) + "]\n"
      "export const ANIME = [" + ', '.join(rows['a']) + "]\n"
      "export const SEA = [" + ', '.join(rows['s']) + "]\n"
      "export const IRAQ = [" + ', '.join(rows['q']) + "]\n")
open(os.path.join(ROOT, 'src', 'lib', 'wallpaperList.js'), 'w').write(js)
size = sum(os.path.getsize(f) for f in glob.glob(os.path.join(OUT, '**', '*.webp'), recursive=True))
print(len(rows['n']), 'nature,', len(rows['a']), 'anime,', len(rows['s']), 'sea,', len(rows['q']), 'iraq,', round(size / 1024), 'KB')
