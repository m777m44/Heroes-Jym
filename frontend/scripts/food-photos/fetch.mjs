#!/usr/bin/env node
// 14.0 — fetches the kitchen's real photos from Wikimedia Commons (src/lib/photos/manifest.js):
// finds each photo's file, checks it is a real photograph under a free licence, downloads it and
// saves two WebP copies — public/food/m/<key>.webp (640 × 480, the big animated picture) and
// public/food/t/<key>.webp (200 × 200, the lists) — plus who took it and its licence
// (src/lib/photos/credits.json: key → [file, author, licence]), which the app shows under every
// photo. state.json remembers which sources each photo came from, so a run only fetches what
// changed.
//
//   node scripts/food-photos/fetch.mjs              only new or changed photos
//   node scripts/food-photos/fetch.mjs --force      every photo again
//   node scripts/food-photos/fetch.mjs --only a,b   just these keys
//   candidates.txt (keys, one per line)             also writes review/<key>.jpg: the best six
//                                                   search results side by side, to choose from
//
// Needs internet and sharp (SHARP_FROM=a folder whose node_modules has it, or an installed one) —
// the "Food photos" workflow runs it and commits what changed. Rejected on the way: drawings,
// paintings, posters, logos, maps and icons (SVG/GIF, or such a name or category), black-and-white
// pictures, small ones, GFDL-only files, and anything Commons files as made by AI — the user asked
// for real photos only. A search prefers files whose name has the words searched for, quality
// images, and files no other photo uses.
import { existsSync, mkdirSync, readFileSync, writeFileSync, rmSync, readdirSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'
import { createRequire } from 'node:module'
import { cleanAuthor } from '../../src/lib/photos/url.js'

const here = dirname(fileURLToPath(import.meta.url))
const front = resolve(here, '..', '..')
const OUT = join(front, 'public', 'food')
const CREDITS = join(front, 'src', 'lib', 'photos', 'credits.json')
const REPORT = join(here, 'report.json')
const STATE = join(here, 'state.json')
const REVIEW = join(here, 'review')
const UA = 'MAHDI-JYM-food-photos/14.0 (https://github.com/m777m44/Heroes-Jym; GitHub Actions) node'
export const SIZE = { m: [640, 480, 62], t: [200, 200, 58] }

const args = process.argv.slice(2)
const flag = n => args.includes(n)
const opt = n => { const i = args.indexOf(n); return i >= 0 ? args[i + 1] : null }

// ---- rules ---------------------------------------------------------------------------------
const BAD_NAME = /\b(logo|logos|logotype|wordmark|icon|emblem|symbol|coat[ _]of[ _]arms|flag|map|locator|diagram|chart|graph|signature|seal|clipart|cartoon|drawing|illustration|sketch|vector|nutrition[ _]facts|label)\b/i
const AI = /(AI[- ]generated|generated by (an )?AI|artificial intelligence|Midjourney|DALL[·-]?E|Stable[ _]Diffusion|Adobe[ _]Firefly|Ideogram|Imagen|Flux[ _]\(|Leonardo\.ai)/i
const OK_MIME = /^image\/(jpeg|png|webp|tiff)$/
const QUALITY = /(Featured pictures|Quality images|Valued images)/i
const NOT_PHOTO = /(botanical illustration|Köhler|Medizinal-Pflanzen|illustrations?\b|drawings?\b|paintings?\b|posters?\b|engravings?\b|lithograph|still life|advertis|clip ?art|diagrams?\b|logos?\b|icons?\b|cartoons?\b|comics?\b|maps? of|herbarium)/i
const STOP = new Set(['the', 'a', 'of', 'and', 'with', 'in', 'on', 'for', 'to', 'bowl', 'plate', 'glass', 'cup'])
/** Big enough: the short side at least 380 px (280 for a file named on purpose) and 170,000 pixels. */
const bigEnough = (ii, named = false) => Math.min(ii.width || 0, ii.height || 0) >= (named ? 280 : 380) && (ii.width || 0) * (ii.height || 0) >= (named ? 100000 : 170000)

/** "w:ar:Title@top" → { kind: 'w', lang: 'ar', value: 'Title' }, focus 'top'. */
export function parseSources(spec) {
  let focus = null
  const m = /@(top|bottom|left|right|centre|center)$/.exec(spec)
  if (m) { focus = m[1] === 'center' ? 'centre' : m[1]; spec = spec.slice(0, m.index) }
  const list = spec.split('|').map(s => s.trim()).filter(Boolean).map(s => {
    const k = s[0], rest = s.slice(2)
    if (k === 'w') {
      const lm = /^([a-z]{2,3}):(.+)$/.exec(rest)
      return lm ? { kind: 'w', lang: lm[1], value: lm[2] } : { kind: 'w', lang: 'en', value: rest }
    }
    if (k === 'f') return { kind: 'f', value: rest.replace(/^File:/i, '') }
    if (k === 's') return { kind: 's', value: rest }
    throw new Error('Unknown source: ' + s)
  })
  return { list, focus }
}

/** Plain text of an extmetadata HTML value. */
export function plain(html, max = 90) {
  const s = String(html || '').replace(/<[^>]*>/g, ' ').replace(/&nbsp;/g, ' ').replace(/&amp;/g, '&').replace(/&quot;/g, '"')
    .replace(/&#0?39;|&apos;/g, '\'').replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&#(\d+);/g, (_, n) => String.fromCodePoint(+n))
    .replace(/\s+/g, ' ').trim()
  return s.length > max ? s.slice(0, max - 1).trimEnd() + '…' : s
}

/** Why a file can't be used (or null): its imageinfo + extmetadata. */
export function rejectReason(name, ii, named = false) {
  if (!ii) return 'missing'
  if (!OK_MIME.test(ii.mime || '')) return 'not a photo (' + ii.mime + ')'
  if (BAD_NAME.test(name.replace(/[_-]/g, ' '))) return 'logo/drawing by name'
  if (!bigEnough(ii, named)) return 'too small (' + ii.width + '×' + ii.height + ')'
  const em = ii.extmetadata || {}
  const cats = (em.Categories && em.Categories.value) || ''
  const desc = (em.ImageDescription && em.ImageDescription.value) || ''
  if (AI.test(cats) || AI.test(plain(desc, 2000))) return 'AI-generated'
  if (NOT_PHOTO.test(cats) || NOT_PHOTO.test(name.replace(/[_-]/g, ' '))) return 'drawing/painting/poster by category'
  const lic = plain(em.LicenseShortName && em.LicenseShortName.value)
  if (!lic) return 'no licence'
  if (/fair use|non-free|copyrighted/i.test(lic)) return 'not free (' + lic + ')'
  if (/^GFDL/i.test(lic)) return 'GFDL only'
  return null
}

/** Words of a search, for matching file names ("incategory:…" and -"…" left out). */
export const queryWords = q => q.replace(/-"[^"]*"|-\S+|incategory:\S+|"/g, ' ').toLowerCase().split(/[^\p{L}\p{N}]+/u).filter(w => w.length > 1 && !STOP.has(w))
/** How many of the words a file name has (whole words, any case). */
export function titleScore(title, words) {
  const t = ' ' + title.toLowerCase().replace(/\.[a-z]+$/, '').replace(/[^\p{L}\p{N}]+/gu, ' ') + ' '
  return words.filter(w => t.includes(' ' + w + ' ') || t.includes(' ' + w + 's ') || t.includes(' ' + w.replace(/s$/, '') + ' ')).length
}
/** A colour photo? — false for black-and-white ones (sharp, on a small copy). */
export async function isColour(sharp, buf) {
  const { data, info } = await sharp(buf, { failOn: 'none' }).resize(48, 48, { fit: 'inside' }).removeAlpha().raw().toBuffer({ resolveWithObject: true })
  const spread = []
  for (let i = 0; i + 2 < data.length; i += info.channels) spread.push(Math.max(data[i], data[i + 1], data[i + 2]) - Math.min(data[i], data[i + 1], data[i + 2]))
  spread.sort((a, b) => a - b)
  return spread[Math.floor(spread.length * 0.9)] >= 12
}

// ---- network -------------------------------------------------------------------------------
const sleep = ms => new Promise(r => setTimeout(r, ms))
let http = async (url, { binary = false } = {}) => {
  for (let i = 0; ; i++) {
    const r = await fetch(url, { headers: { 'User-Agent': UA, 'Api-User-Agent': UA } })
    if (r.ok) return binary ? Buffer.from(await r.arrayBuffer()) : r.json()
    if (i >= 5 || ![429, 500, 502, 503, 504].includes(r.status)) throw new Error(r.status + ' ' + url)
    await sleep(2000 * (i + 1) + (r.status === 429 ? 8000 : 0))
  }
}
/** For tests: swap the network. */
export const setHttp = fn => { http = fn }

const api = (host, params) => http(`https://${host}/w/api.php?` + new URLSearchParams({ format: 'json', formatversion: '2', ...params }))
const COMMONS = 'commons.wikimedia.org'

/** Wikipedia lead images (free only): Map "lang:Title" → file name. */
async function leadImages(titlesByLang) {
  const out = new Map()
  for (const [lang, titles] of Object.entries(titlesByLang)) {
    const uniq = [...new Set(titles)]
    for (let i = 0; i < uniq.length; i += 50) {
      const batch = uniq.slice(i, i + 50)
      const j = await api(lang + '.wikipedia.org', { action: 'query', prop: 'pageimages', piprop: 'name', pilicense: 'free', redirects: '1', titles: batch.join('|') })
      const q = j.query || {}
      const back = new Map(batch.map(t => [t, t]))
      for (const n of q.normalized || []) for (const [k, v] of back) if (v === n.from) back.set(k, n.to)
      for (const rd of q.redirects || []) for (const [k, v] of back) if (v === rd.from) back.set(k, rd.to)
      const byTitle = new Map((q.pages || []).map(p => [p.title, p.pageimage]))
      for (const [orig, final] of back) { const f = byTitle.get(final); if (f) out.set(lang + ':' + orig, f) }
    }
  }
  return out
}

/**
 * Commons search: file names, best first — the most search words in the file name, then quality
 * images, then the search's own order.
 */
async function search(q, n = 12) {
  const j = await api(COMMONS, {
    action: 'query', generator: 'search', gsrsearch: q + ' filetype:bitmap', gsrnamespace: '6', gsrlimit: String(n),
    prop: 'imageinfo|categories', iiprop: 'size|mime', clshow: '!hidden', cllimit: 'max',
    clcategories: 'Category:Quality images|Category:Featured pictures on Wikimedia Commons|Category:Valued images',
  })
  const words = queryWords(q)
  const pages = ((j.query && j.query.pages) || []).filter(p => p.imageinfo && p.imageinfo[0])
  return pages.filter(p => {
    const ii = p.imageinfo[0]
    return OK_MIME.test(ii.mime) && bigEnough(ii) && !BAD_NAME.test(p.title.replace(/[_-]/g, ' '))
  }).map(p => ({ name: p.title.replace(/^File:/, ''), score: titleScore(p.title.replace(/^File:/, ''), words) * 10 + ((p.categories || []).length ? 4 : 0) - p.index * 0.1 }))
    .sort((a, b) => b.score - a.score).map(x => x.name)
}

/** imageinfo (+ a 960 px thumbnail URL and the licence) for up to 50 files at a time. */
async function infos(names) {
  const out = new Map()
  const uniq = [...new Set(names)]
  for (let i = 0; i < uniq.length; i += 50) {
    const batch = uniq.slice(i, i + 50)
    const j = await api(COMMONS, {
      action: 'query', titles: batch.map(n => 'File:' + n).join('|'), prop: 'imageinfo', iiprop: 'url|size|mime|extmetadata',
      iiurlwidth: '960', iiextmetadatafilter: 'Artist|Credit|LicenseShortName|Categories|ImageDescription',
    })
    const q = j.query || {}
    const back = new Map(batch.map(n => ['File:' + n, n]))
    for (const nn of q.normalized || []) if (back.has(nn.from)) { back.set(nn.to, back.get(nn.from)) }
    for (const p of q.pages || []) {
      const ii = p.imageinfo && p.imageinfo[0]
      const orig = back.get(p.title) || p.title.replace(/^File:/, '')
      if (ii) out.set(orig, { ...ii, title: p.title.replace(/^File:/, '') })
    }
  }
  return out
}

// ---- main ----------------------------------------------------------------------------------
export async function run({ rows, credits = {}, state = {}, force = false, only = null, candidates = [], sharp, log = console.log }) {
  const report = { picked: {}, missing: {}, rejected: {} }
  const todo = rows.filter(([key, src]) => {
    if (only && !only.includes(key)) return false
    return force || !credits[key] || state[key] !== src || !existsSync(join(OUT, 'm', key + '.webp')) || !existsSync(join(OUT, 't', key + '.webp'))
  })
  log(`${rows.length} photos in the manifest — ${todo.length} to fetch`)
  const parsed = new Map(todo.map(([key, src]) => [key, parseSources(src)]))
  // files other photos already show: each photo should be its own
  const used = new Map()
  for (const [k, c] of Object.entries(credits)) if (!parsed.has(k) && c) used.set(c[0], k)
  // 1. Wikipedia lead images, all at once
  const titles = {}
  for (const { list } of parsed.values()) for (const s of list) if (s.kind === 'w') (titles[s.lang] = titles[s.lang] || []).push(s.value)
  const leads = await leadImages(titles)
  // 2. candidates per photo, in order (a file named on purpose is marked)
  const cands = new Map()
  for (const [key, { list }] of parsed) {
    const out = [], seen = new Set()
    const push = (name, named) => { const n = name.replace(/_/g, ' '); if (!seen.has(n)) { seen.add(n); out.push({ name: n, named }) } }
    for (const s of list) {
      if (s.kind === 'f') push(s.value, true)
      else if (s.kind === 'w') { const f = leads.get(s.lang + ':' + s.value); if (f) push(f, false) }
      else if (s.kind === 's') { try { for (const n of await search(s.value)) push(n, false) } catch (e) { log('search failed: ' + s.value + ' — ' + e.message) } }
    }
    cands.set(key, out)
  }
  // 3. information on the first few candidates of every photo, in batches
  const info = new Map()
  const fetchInfo = async names => { const need = [...new Set(names)].filter(n => !info.has(n)); if (need.length) for (const [n, ii] of await infos(need)) info.set(n.replace(/_/g, ' '), ii) }
  await fetchInfo([...cands.values()].flatMap(l => l.slice(0, 4).map(c => c.name)))
  // 4. per photo: the first candidate that passes, downloaded, still a colour photo → two WebP copies
  mkdirSync(join(OUT, 'm'), { recursive: true }); mkdirSync(join(OUT, 't'), { recursive: true })
  const reject = (key, name, why) => { (report.rejected[key] = report.rejected[key] || []).push(name + ' — ' + why) }
  const queue = [...todo]
  const work = async () => {
    for (let row; (row = queue.shift());) {
      const [key, src] = row
      const list = cands.get(key) || []
      let done = false
      for (let i = 0; i < list.length && i < 12 && !done; i++) {
        const c = list[i]
        if (!info.has(c.name)) await fetchInfo(list.slice(i, i + 4).map(x => x.name))
        const ii = info.get(c.name)
        const why = rejectReason(c.name, ii, c.named)
        if (why) { reject(key, c.name, why); continue }
        const file = ii.title || c.name
        if (!c.named && used.has(file) && used.get(file) !== key) { reject(key, c.name, 'already the photo of ' + used.get(file)); continue }
        try {
          const buf = await http(ii.thumburl || ii.url, { binary: true })
          if (!(await isColour(sharp, buf))) { reject(key, c.name, 'black and white'); continue }
          const position = parsed.get(key).focus || sharp.strategy.attention
          for (const [dir, [w, h, q]] of Object.entries(SIZE)) {
            await sharp(buf, { failOn: 'none' }).rotate().resize(w, h, { fit: 'cover', position })
              .webp({ quality: q, effort: 6, smartSubsample: true }).toFile(join(OUT, dir, key + '.webp'))
          }
          const em = ii.extmetadata || {}
          credits[key] = [file, cleanAuthor(plain(em.Artist && em.Artist.value, 160) || plain(em.Credit && em.Credit.value, 160)).slice(0, 90), plain(em.LicenseShortName && em.LicenseShortName.value, 40)]
          state[key] = src
          used.set(file, key)
          report.picked[key] = file
          done = true
        } catch (e) { reject(key, c.name, 'download failed: ' + e.message) }
      }
      if (!done) report.missing[key] = (report.rejected[key] || []).length ? 'every candidate was rejected' : 'nothing found'
    }
  }
  await Promise.all([work(), work(), work(), work()])
  // 5. photos no longer in the manifest go
  const keys = new Set(rows.map(r => r[0]))
  for (const k of Object.keys(credits)) if (!keys.has(k)) delete credits[k]
  for (const k of Object.keys(state)) if (!keys.has(k)) delete state[k]
  for (const dir of Object.keys(SIZE)) {
    const d = join(OUT, dir)
    if (existsSync(d)) for (const f of readdirSync(d)) if (f.endsWith('.webp') && !keys.has(f.slice(0, -5))) rmSync(join(d, f))
  }
  // 6. review sheets: the best six candidates of each key in candidates.txt
  if (candidates.length) {
    rmSync(REVIEW, { recursive: true, force: true }); mkdirSync(REVIEW, { recursive: true })
    for (const key of candidates) {
      const row = rows.find(r => r[0] === key)
      const words = row ? parseSources(row[1]).list.filter(s => s.kind === 's').map(s => s.value) : []
      if (!words.length && row) words.push(key)
      const names = []
      for (const w of words) { try { names.push(...await search(w, 14)) } catch {} }
      const list = [...new Set(names)].slice(0, 6)
      const ii = await infos(list)
      const tiles = []
      for (const n of list) {
        const x = ii.get(n)
        if (!x || rejectReason(n, x)) continue
        try {
          const b = await http(x.thumburl || x.url, { binary: true })
          tiles.push({ n, img: await sharp(b, { failOn: 'none' }).rotate().resize(220, 165, { fit: 'cover' }).jpeg({ quality: 70 }).toBuffer() })
        } catch {}
      }
      if (!tiles.length) continue
      await sharp({ create: { width: 220 * tiles.length + 4 * (tiles.length - 1), height: 165, channels: 3, background: '#000' } })
        .composite(tiles.map((t, i) => ({ input: t.img, left: i * 224, top: 0 }))).jpeg({ quality: 72 }).toFile(join(REVIEW, key + '.jpg'))
      writeFileSync(join(REVIEW, key + '.txt'), tiles.map((t, i) => (i + 1) + '\t' + t.n).join('\n') + '\n')
    }
  }
  return { credits, state, report }
}

if (import.meta.url === pathToFileURL(process.argv[1] || '').href) {
  const sharp = createRequire(process.env.SHARP_FROM ? join(resolve(process.env.SHARP_FROM), 'x.js') : import.meta.url)('sharp')
  const { PHOTO_ROWS } = await import(pathToFileURL(join(front, 'src', 'lib', 'photos', 'manifest.js')).href)
  const raw = existsSync(CREDITS) ? JSON.parse(readFileSync(CREDITS, 'utf8')) : {}
  const state = existsSync(STATE) ? JSON.parse(readFileSync(STATE, 'utf8')) : {}
  const credits = {}
  for (const [k, v] of Object.entries(raw)) {   // 14.0 first run wrote { f, a, l, s }
    if (Array.isArray(v)) credits[k] = v
    else { credits[k] = [v.f, v.a, v.l]; if (v.s && !state[k]) state[k] = v.s }
  }
  const cfile = join(here, 'candidates.txt')
  const candidates = existsSync(cfile) ? readFileSync(cfile, 'utf8').split(/\s+/).map(s => s.trim()).filter(s => s && !s.startsWith('#')) : []
  const only = opt('--only') ? opt('--only').split(',') : null
  const { report } = await run({ rows: PHOTO_ROWS, credits, state, force: flag('--force'), only, candidates, sharp })
  const sorted = Object.fromEntries(Object.keys(credits).sort().map(k => [k, credits[k]]))
  const lines = o => '{\n' + Object.entries(o).map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)}`).join(',\n') + '\n}\n'
  writeFileSync(CREDITS, lines(sorted))
  writeFileSync(STATE, lines(Object.fromEntries(Object.keys(state).sort().map(k => [k, state[k]]))))
  writeFileSync(REPORT, JSON.stringify(report, null, 1) + '\n')
  const miss = Object.keys(report.missing)
  console.log(`✓ ${Object.keys(report.picked).length} fetched · ${miss.length} missing · ${Object.keys(sorted).length} photos in all`)
  for (const k of miss) console.log(`::warning title=No photo for ${k}::${report.missing[k]} — ${(report.rejected[k] || []).join(' / ')}`)
}
